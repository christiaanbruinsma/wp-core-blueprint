function assert_placeholder_parity(string $locale, string $source, string $translation): void {
    $pattern = '/\{\{[^{}]+\}\}|%(?:\d+\$)?s/';
    preg_match_all($pattern, $source, $source_matches);
    preg_match_all($pattern, $translation, $translation_matches);

    $expected = $source_matches[0] ?? [];
    $actual = $translation_matches[0] ?? [];
    sort($expected, SORT_STRING);
    sort($actual, SORT_STRING);

    if ($expected !== $actual) {
        throw new RuntimeException(sprintf(
            'Placeholder mismatch in %s for source: %s',
            $locale,
            str_replace("\n", '\\n', $source)
        ));
    }
}

/** @param array<string,mixed> $catalog */
function render_catalog(array $catalog): string {
    $out = "<?php\nreturn [\n";

    foreach ($catalog as $key => $value) {
        if ('messages' === $key) {
            if (!is_array($value)) {
                throw new RuntimeException('Catalog messages must be an array.');
            }
            $out .= "    'messages' => [\n";
            foreach ($value as $source => $translation) {
                if (!is_string($source) || !is_string($translation)) {
                    throw new RuntimeException('Catalog messages must contain only string keys and values.');
                }
                $out .= '        ' . php_string($source) . ' => ' . php_string($translation) . ",\n";
            }
            $out .= "    ],\n";
            continue;
        }

        if (!is_string($key) || !is_string($value)) {
            throw new RuntimeException('Catalog metadata must contain only string keys and values.');
        }
        $out .= '    ' . php_string($key) . ' => ' . php_string($value) . ",\n";
    }

    return $out . "];\n";
}

function php_string(string $value): string {
    if (str_contains($value, "\n") || str_contains($value, "\r") || str_contains($value, "\t")) {
        $escaped = str_replace(
            ['\\', '"', '$', "\r", "\n", "\t"],
            ['\\\\', '\\"', '\\$', '\\r', '\\n', '\\t'],
            $value
        );
        return '"' . $escaped . '"';
    }

    return "'" . str_replace(['\\', "'"], ['\\\\', "\\'"], $value) . "'";
}
