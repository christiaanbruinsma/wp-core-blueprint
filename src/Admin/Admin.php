	/**
	 * Expose the authoritative active Scanner job to the admin module.
	 *
	 * localStorage is only a convenience cache. A scheduled/API scan can exist
	 * without it, and a browser may retain an older job id after recovery.
	 */
	private static function core_scanner_active_job_data(): ?array {
		if ( ! class_exists( \CB\Core\Integrity\Scanner\ScanJobStatus::class ) ) {
			return null;
		}

		$job = \CB\Core\Integrity\Scanner\ScanJobStatus::active_job();
		if ( ! is_array( $job ) ) {
			return null;
		}

		return [
			'jobId'     => (string) ( $job['job_id'] ?? '' ),
			'startedAt' => (float) ( $job['started_at_micro'] ?? microtime( true ) ),
		];
	}

	// ─── Menu icon helper ────────────────────────────────────────────────

	private static function get_menu_icon(): string {
		$icon_path = CB_CORE_DIR . 'assets/core-blueprint-icon.svg';
		if ( ! file_exists( $icon_path ) ) {
			return 'dashicons-shield-alt';
		}
		$svg = file_get_contents( $icon_path );
		if ( false === $svg ) {
			return 'dashicons-shield-alt';
		}
		return 'data:image/svg+xml;base64,' . base64_encode( $svg );
	}
