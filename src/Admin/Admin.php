				'@cb-core/mail-log',
				CB_CORE_URL . 'assets/js/features/mail-log.js',
				[ '@cb-core/modal' ],
				CB_CORE_VERSION
			);
		}

		if ( $is_media_formats_page ) {
			wp_enqueue_script_module(
				'@cb-core/media-formats',
				CB_CORE_URL . 'assets/js/features/media-formats.js',
				[],
				CB_CORE_VERSION
			);
		}

		if ( $is_content_models_page ) {
			\CB\Core\UI\Assets::enqueue_icon_picker( \CB\Core\UI\Assets::ICON_PICKER_PRESENTATION_CORE );
			\CB\Core\UI\Assets::enqueue_capability_picker( \CB\Core\UI\Assets::CAPABILITY_PICKER_PRESENTATION_CORE );
