				'@cb-core/content-models',
				CB_CORE_URL . 'assets/js/features/content-models.js',
				$content_models_deps,
				CB_CORE_VERSION
			);
			add_filter(
				'script_module_data_@cb-core/content-models',
				static function ( array $existing ): array {
					return array_merge( $existing, [
						'ajaxUrl' => admin_url( 'admin-ajax.php' ),
						'i18n' => [
							'typeChangeTitle'   => __( 'Change field type?', 'core-blueprint' ),
							'typeChangeBody'    => __( 'Changing a field type can change how existing WordPress metadata is interpreted. Core Blueprint will not delete or migrate existing field values. If this field is new or unused, changing the type is normally safe. If it already contains data, review affected content after saving.', 'core-blueprint' ),
							'typeChangeConfirm' => __( 'Change field type', 'core-blueprint' ),
							'typeChangeCancel'  => __( 'Keep current type', 'core-blueprint' ),
							'quickSaving'       => __( 'Saving…', 'core-blueprint' ),
							'quickSaved'        => __( 'Field saved.', 'core-blueprint' ),
							'quickError'        => __( 'The field could not be saved.', 'core-blueprint' ),
							'requiredLabel'     => __( 'required', 'core-blueprint' ),
							'restEnabled'       => __( 'Enabled', 'core-blueprint' ),
							'restDisabled'      => __( 'Disabled', 'core-blueprint' ),
						],
					] );
				}
			);
		}


		// ─── Scrollbar (1.6.4-dev) ───────────────────────────────────────
		//
		// Suite-wide thin scrollbar primitive. Loaded right after tokens
		// and before any other component or page CSS so the styling
		// reaches every scrollable Core Admin surface. Asset handles are
		// implementation details; extension pages consume the registered
		// Core Admin shell/semantic requirements rather than handle names.
		wp_enqueue_style(
			'cb-core-css-scrollbar',
			CB_CORE_URL . 'assets/css/components/scrollbar.css',
			[ 'cb-core-css-tokens' ],
			CB_CORE_VERSION
		);

		// ─── Meta strip (1.6.4-dev) ──────────────────────────────────────
		//
		// Suite-wide page-metadata strip - the row of contextual facts
		// that sits under a page title (totals, retention, access
		// rules, export options). Generic class names (cb-core-meta /
		// cb-core-meta__item) - not log-specific - so registered Core Admin
		// pages can reuse the same markup without depending on private handles.
		wp_enqueue_style(
			'cb-core-css-meta',
			CB_CORE_URL . 'assets/css/components/meta.css',
			[ 'cb-core-css-tokens' ],
			CB_CORE_VERSION
		);

		// ─── Mode switcher (1.6.4-dev) ───────────────────────────────────
		//
		// Suite-wide reading-mode switcher (Plain / Technical / Sync).
		// Identical markup + behaviour across every CB page and the
		// HUD - one mental model for the user, one source of truth
		// for the markup contract. Two size variants via the
		// --compact modifier; see UI::render_mode_switcher() for the
		// rendering API.
		wp_enqueue_style(
			'cb-core-css-mode-switcher',
			CB_CORE_URL . 'assets/css/components/mode-switcher.css',
			[ 'cb-core-css-tokens' ],
			CB_CORE_VERSION
		);

		// ─── Filter bar (1.6.4-dev) ──────────────────────────────────────
		//
		// Suite-wide filter bar - the row of labelled controls above
		// any list/table view (Logs, Notes, Reports, Hub fleet, …).
		// One uniform control height (--cb-control-height), labels
		// for every field including the actions cluster, responsive
		// flex-wrap on narrow viewports. Depends on mode-switcher
		// so the ms-specific filter-bar overrides resolve in order.
		wp_enqueue_style(
			'cb-core-css-filter-bar',
			CB_CORE_URL . 'assets/css/components/filter-bar.css',
			[ 'cb-core-css-tokens', 'cb-core-css-mode-switcher' ],
			CB_CORE_VERSION
		);

		// ─── Layout + foundational components ─────────────────────────────
		//
		// Layout primitives (page-wrap, title, intro, h2) and components
		// that other components or pages may override later in the
		// cascade. Loading them in this fixed order is what gives us
		// predictable specificity even though selectors are flat.
		wp_enqueue_style(
			'cb-core-css-layout',
			CB_CORE_URL . 'assets/css/layout.css',
			[ 'cb-core-css-tokens' ],
			CB_CORE_VERSION
		);
		$cb_core_css_components_foundation = [
			'tile-grid',
			'kv-tables',
			'badges',
			'rack-modules',
			'inert-text',
			'meta-bar',
			'panels',
			'utility',
			'policy-table',
			'overview-framework',
			'form-status',
			'disclosure',
			'hud',
		];
		foreach ( $cb_core_css_components_foundation as $component ) {
			wp_enqueue_style(
				'cb-core-css-' . $component,
				CB_CORE_URL . 'assets/css/components/' . $component . '.css',
				[ 'cb-core-css-tokens' ],
				CB_CORE_VERSION
			);
		}

		// ─── Components introduced in stap 5.1 ────────────────────────────
		//
		// Newer components designed against the cb-* token contract from
		// the start. Loaded after foundation components so they can
		// override default styling where the new component is intended
		// to supersede a foundation pattern (e.g. .cb-core-modal supersedes
		// older modal patterns).
		$cb_core_css_components_modern = [
			'cards',
			'modals',
			'toasts',
			'buttons',
			'interactive-surfaces',
			'state-badges',
			'status-indicators',
			'spinner',
			'empty-state',
			'nav-tabs',
			'table-cols',
			'actions',
			'log-table',
			'field',
			'radio-card',
			'master-switch',
			'form-controls',
			'choice-group',
			'status-menu',
			'notices',
		];
		foreach ( $cb_core_css_components_modern as $component ) {
			wp_enqueue_style(
				'cb-core-css-' . $component,
				CB_CORE_URL . 'assets/css/components/' . $component . '.css',
				[ 'cb-core-css-tokens' ],
				CB_CORE_VERSION
			);
		}

		// ─── Theme-level overrides ────────────────────────────────────────
		//
		// Canvas overrides target WP admin chrome (page background, admin
		// notices) per CB theme. Theme-level concern, not page or
		// component. Loaded after components so theme-specific surface
		// colours apply on top of component baselines.
		wp_enqueue_style(
			'cb-core-css-theme-canvas',
			CB_CORE_URL . 'assets/css/themes/canvas.css',
			[ 'cb-core-css-tokens' ],
			CB_CORE_VERSION
		);

		// ─── Page-specific stylesheets ────────────────────────────────────
		//
		// Per-page styling. Loaded last so any page-specific overrides on
		// shared components (banners, badges, kv-tables) take precedence.
		// Page selectors are unique to each page so cascade collisions
		// between pages are not expected.
		//
		// Naming convention: top-level admin pages get a single-word
		// filename (dashboard, logs, reports, privacy). Pages that are
		// tabs of a parent page use {parent}-{tab}.css so the structure
		// is visible from the file listing.
		$cb_core_css_pages = [
			'dashboard',
			'logs',
			'reports',
			'preferences',
			'privacy',
			'appearance',
			'language',
			'security',
			'preferences-notifications',
			'preferences-permissions',
			'preferences-cli',
			'console',
			'mail',
			'safeguards-modules',
