		if ( $is_hud_menu_preferences ) {
			wp_enqueue_style(
				'cb-core-css-page-preferences-floating-menu',
				CB_CORE_URL . 'assets/css/pages/preferences-floating-menu.css',
				[ 'cb-core-css-tokens', 'cb-core-css-buttons', 'cb-core-css-form-controls', 'cb-core-css-state-badges', 'cb-core-css-page-preferences' ],
				CB_CORE_VERSION
			);
		}

		// ─── ES module layer (v1.1.1) ───────────────────────────────────
		//
		// CB Base ships native ES script-modules. Each module is registered
		// under the WP-conventional `@cb-core/{name}` ID (mirrors WP core's
		// `@wordpress/...` namespace). Per-module server-side data is
		// delivered via the official `script_module_data_{$id}` filter
		// (introduced in WP 6.7) - WP prints a `<script type="application/json"
		// id="wp-script-module-data-@cb-core/{name}">…</script>` tag that
		// each module reads via DOM lookup at runtime.
		//
		// Runtime cross-plugin API surface (modal, toast, qs, qsa, apiPost,
		// setTheme, setLocale, copyToClipboard, confirmPassword, apiVersion)
