	public static function init(): void {
		add_action( 'admin_menu',            [ __CLASS__, 'register_parent_menu' ], 5 );
		add_action( 'admin_menu',            [ __CLASS__, 'remove_duplicate_submenu' ], 999 );
		add_action( 'admin_enqueue_scripts', [ __CLASS__, 'enqueue_assets' ] );

		// Register Core Blueprint's own pages at the right moment. Sibling
		// CB plugins do the same via this hook.
		add_action( 'cb_core_register_pages', [ __CLASS__, 'register_foundation_pages' ] );
	}

	// ─── Parent menu ──────────────────────────────────────────────────────

	/**
	 * Register the Core Blueprint top-level menu if no sibling CB plugin has
	 * already done so. Defensive - multiple CB plugins might race, and the
	 * first one wins.
	 */
	public static function register_parent_menu(): void {
		global $menu;

		$parent_exists = false;
		if ( is_array( $menu ) ) {
			foreach ( $menu as $item ) {
				if ( isset( $item[2] ) && CB_CORE_PARENT_MENU === $item[2] ) {
					$parent_exists = true;
					break;
				}
			}
		}

		if ( ! $parent_exists ) {
			add_menu_page(
				'Core Blueprint',
				'Core Blueprint',
				/**
				 * Filter: cb_core_menu_capability
				 *
				 * The capability required to see Core Blueprint admin pages.
				 * Defaults to 'manage_options'.
				 */
				(string) apply_filters( 'cb_core_menu_capability', 'manage_options' ),
				CB_CORE_PARENT_MENU,
				[ __CLASS__, 'render_parent_landing' ],
				self::get_menu_icon(),
				3
			);
		}
	}

	/**
	 * Called when a user clicks the Core Blueprint parent menu item itself.
	 * Delegates to the registered Dashboard page, falling back to a simple
	 * notice when no dashboard is available.
	 */
	public static function render_parent_landing(): void {
		if ( class_exists( Dashboard::class ) ) {
			$dashboard = new Dashboard();
			$dashboard->render();
			return;
		}
		echo '<div class="wrap"><h1>Core Blueprint</h1><p>';
		esc_html_e( 'Dashboard not available.', 'core-blueprint' );
		echo '</p></div>';
	}

	/**
	 * Register Core Blueprint's own pages with the registry. Called from the
	 * cb_core_register_pages action so the timing aligns with admin_menu.
	 *
	 * Submenu order is controlled by each page's position(). Resulting
	 * sidebar order:
	 *   Dashboard (auto-gen, slug = parent)
	 *   Logs         - position 20
	 *   Safeguards   - position 30
	 *   Preferences  - position 90
	 *   Beacon      - optional extension page, position 100
	 */
	public static function register_foundation_pages(): void {
		// Dashboard is NOT registered here. It lives as the auto-generated
		// first submenu that add_menu_page() creates in register_parent_menu().
		// That auto-gen entry has slug == parent slug, so WordPress uses it
		// as the parent-click landing page. Its callback is render_parent_landing,
		// which instantiates Dashboard and renders it. remove_duplicate_submenu()
		// below relabels the auto-gen to "Dashboard" (instead of the parent's
		// "Core Blueprint" label) for cleaner sidebar presentation.

		PageRegistry::register_base( new Logs() );
		PageRegistry::register_base( new Safeguards() );
		PageRegistry::register_base( new Preferences() );
	}

	public static function remove_duplicate_submenu(): void {
		global $submenu;

		// The first submenu under the parent is auto-generated by add_menu_page()
		// and inherits the parent's "Core Blueprint" label, which is ugly in the
		// sidebar. Rewrite its label + title to "Dashboard" in place - keeping
		// the entry (and its callback = render_parent_landing, which renders
		// Dashboard) so clicking the parent menu still lands on the Dashboard.
		if ( isset( $submenu[ CB_CORE_PARENT_MENU ] ) ) {
			foreach ( $submenu[ CB_CORE_PARENT_MENU ] as $i => $item ) {
				if ( isset( $item[2] ) && CB_CORE_PARENT_MENU === $item[2] ) {
					$submenu[ CB_CORE_PARENT_MENU ][ $i ][0] = __( 'Dashboard', 'core-blueprint' );
					if ( isset( $submenu[ CB_CORE_PARENT_MENU ][ $i ][3] ) ) {
						$submenu[ CB_CORE_PARENT_MENU ][ $i ][3] = __( 'Dashboard', 'core-blueprint' );
					}
					break;
				}
			}
		}

		// Suppress the Core Blueprint Theme's Site Mode submenu - this plugin
		// owns access mode now. Safe no-op if the theme is not active or has
		// already been updated to drop its own submenu.
		remove_submenu_page( CB_CORE_PARENT_MENU, 'core-blueprint-site-mode' );
	}

	// ─── Asset enqueuing ─────────────────────────────────────────────────

	public static function enqueue_assets( string $hook ): void {
		// Detect Core Blueprint screens via three mechanisms (any match wins):
		//   1. Registry-tracked hook_suffixes - pages that registered
		//      themselves via PageRegistry
		//   2. The parent toplevel hook
		//   3. Pattern match - any 'core-blueprint_page_cb-*' or
		//      'core-blueprint_page_core-blueprint-*' hook, catches pages
		//      registered by sibling CB plugins (Invoice, Access Control,
		//      Protected Content) even when they don't go through the registry.
		$registry_hooks = PageRegistry::all_hook_suffixes();
		$is_cb_screen = in_array( $hook, $registry_hooks, true )
			|| $hook === 'toplevel_page_' . CB_CORE_PARENT_MENU
			|| ( 0 === strpos( $hook, CB_CORE_PARENT_MENU . '_page_cb-' ) )
			|| ( 0 === strpos( $hook, CB_CORE_PARENT_MENU . '_page_core-blueprint-' ) );

		if ( ! $is_cb_screen ) {
			return;
		}

		// ─── Tokens (1.1.0) ──────────────────────────────────────────────
		//
		// Design tokens (--cb-*) live in their own stylesheet so they
		// can be enqueued ahead of everything else, and so portal
		// elements (dialogs, toasts) appended outside .cb-core-wrap
		// can resolve them via html[data-cb-theme="..."] scope. See
		// the comment block at the top of tokens.css for the scope
		// rationale.
		wp_enqueue_style(
			'cb-core-css-tokens',
			CB_CORE_URL . 'assets/css/tokens.css',
			[],
			CB_CORE_VERSION
		);

		// Shared Lucide primitive. Kept behind UI\Assets so standalone
		// WordPress admin pages can opt into icons without the Core Admin Theme.
		\CB\Core\UI\Assets::enqueue_icons();

		// Registered Core Admin pages may declare semantic shared-UI requirements.
		// PageRegistry resolves those identifiers to private assets; extensions never
		// depend on handles or filenames. The legacy sibling-pattern detection above
		// remains transitional until BASE-10E and is not a public screen contract.
		PageRegistry::enqueue_requirements_for_hook( $hook );

		// Preferences → CLI consumes the shared Clipboard Foundation. Keep the
		// clipboard runtime scoped to this tab rather than loading it across all
		// Core Admin screens.
		$screen_context     = ScreenContext::from_request( $hook );
		$current_page       = $screen_context->page();
		$current_tab        = $screen_context->tab();
		$is_cli_preferences      = 'core-blueprint-preferences' === $current_page && 'cli' === $current_tab;
		$is_hud_menu_preferences = 'core-blueprint-preferences' === $current_page && 'floating-menu' === $current_tab;
		$is_mail_settings        = 'core-blueprint-mail' === $current_page && ( '' === $current_tab || 'settings' === $current_tab );
		$is_mail_test       = 'core-blueprint-mail' === $current_page && 'test' === $current_tab;
		$is_mail_log        = ( 'core-blueprint-mail' === $current_page && 'logs' === $current_tab )
			|| ( self::LOGS_SLUG === $current_page && 'mail' === $current_tab );
		$current_view       = $screen_context->view();
		$is_content_models_page = 'core-blueprint-content-models' === $current_page;
		$is_media_formats_page = 'core-blueprint-media-formats' === $current_page;
		$is_content_models_field_groups = $is_content_models_page && 'field-groups' === $current_tab && in_array( $current_view, [ 'edit', 'field' ], true );
		$is_access_mode_page = 'core-blueprint-safeguards' === $current_page && 'access-mode' === $current_tab;

		if ( $is_access_mode_page ) {
			\CB\Core\UI\Assets::enqueue_object_picker( \CB\Core\UI\Assets::OBJECT_PICKER_PRESENTATION_CORE );
			\CB\Core\UI\Assets::enqueue_time_picker( \CB\Core\UI\Assets::TIME_PICKER_PRESENTATION_CORE );
		}

		if ( $is_cli_preferences ) {
			\CB\Core\UI\Assets::enqueue_clipboard( \CB\Core\UI\Assets::CLIPBOARD_PRESENTATION_CORE );

			wp_enqueue_script_module(
				'@cb-core/preferences-cli',
				CB_CORE_URL . 'assets/js/features/preferences-cli.js',
				[ '@cb-core/clipboard' ],
				CB_CORE_VERSION
			);
			add_filter(
				'script_module_data_@cb-core/preferences-cli',
				static function ( array $existing ): array {
					return array_merge( $existing, [
						'ajaxUrl' => admin_url( 'admin-ajax.php' ),
						'i18n' => [
							'copyCommand' => __( 'Copy command', 'core-blueprint' ),
						],
					] );
				}
			);
		}

		if ( $is_hud_menu_preferences ) {
			wp_enqueue_script_module(
				'@cb-core/preferences-floating-menu',
				CB_CORE_URL . 'assets/js/features/preferences-floating-menu.js',
				[],
				CB_CORE_VERSION
			);
			add_filter(
				'script_module_data_@cb-core/preferences-floating-menu',
				static function ( array $existing ): array {
					return array_merge( $existing, [
						'i18n' => [
							'labelRequired' => __( 'Enter a label for the custom link.', 'core-blueprint' ),
							'urlInvalid'    => __( 'Enter a valid http or https URL.', 'core-blueprint' ),
							'sectionInvalid'=> __( 'Choose an available menu section.', 'core-blueprint' ),
						],
					] );
				}
			);
		}

		if ( $is_mail_settings ) {
			wp_enqueue_script_module(
				'@cb-core/mail-settings',
				CB_CORE_URL . 'assets/js/features/mail-settings.js',
				[],
				CB_CORE_VERSION
			);
