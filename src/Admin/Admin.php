		foreach ( $cb_core_css_pages as $page ) {
			wp_enqueue_style(
				'cb-core-css-page-' . $page,
				CB_CORE_URL . 'assets/css/pages/' . $page . '.css',
				[ 'cb-core-css-tokens' ],
